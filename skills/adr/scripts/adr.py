#!/usr/bin/env python3
"""Manage numbered Architecture Decision Records. Stdlib only.

  adr.py new "Title" [--status Proposed] [--deciders "agent"]
  adr.py list
  adr.py status <n> <Proposed|Accepted|Rejected|Deprecated|Superseded>
  adr.py supersede <n> "New title"
  adr.py index
Global: --dir docs/adr
"""
import argparse
import datetime as dt
import re
import sys
from pathlib import Path

TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "template.md"
STATUSES = ["Proposed", "Accepted", "Rejected", "Deprecated", "Superseded"]
FILE_RE = re.compile(r"^(\d{4})-.+\.md$")


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60] or "decision"


def records(d):
    out = []
    for p in sorted(d.glob("*.md")):
        m = FILE_RE.match(p.name)
        if not m:
            continue
        text = p.read_text(encoding="utf-8")
        title = re.search(r"^# ADR-\d+:\s*(.+)$", text, re.M)
        status = re.search(r"^- \*\*Status:\*\*\s*(.+)$", text, re.M)
        date = re.search(r"^- \*\*Date:\*\*\s*(.+)$", text, re.M)
        out.append({
            "n": int(m.group(1)), "path": p,
            "title": title.group(1).strip() if title else p.stem,
            "status": status.group(1).strip() if status else "?",
            "date": date.group(1).strip() if date else "",
        })
    return out


def find(d, n):
    for r in records(d):
        if r["n"] == n:
            return r
    sys.exit(f"ADR {n} not found in {d}")


def set_status(path, status):
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"^(- \*\*Status:\*\*\s*).+$", lambda m: m.group(1) + status, text, count=1, flags=re.M)
    path.write_text(text, encoding="utf-8")


def create(d, title, status, deciders, supersedes=None):
    d.mkdir(parents=True, exist_ok=True)
    n = max([r["n"] for r in records(d)] or [0]) + 1
    sup = f"- **Supersedes:** [ADR-{supersedes['n']:04d}]({supersedes['path'].name})\n" if supersedes else ""
    body = (TEMPLATE.read_text(encoding="utf-8")
            .replace("{{number}}", f"{n:04d}").replace("{{title}}", title)
            .replace("{{status}}", status).replace("{{date}}", dt.date.today().isoformat())
            .replace("{{deciders}}", deciders).replace("{{supersedes}}", sup))
    path = d / f"{n:04d}-{slugify(title)}.md"
    path.write_text(body, encoding="utf-8")
    return n, path


def write_index(d):
    rows = records(d)
    lines = ["# Architecture Decision Records", "",
             "Generated by `adr.py index`. One file per decision; accepted ADRs are never edited, only superseded.", "",
             "| # | Title | Status | Date |", "|---|-------|--------|------|"]
    for r in rows:
        lines.append(f"| {r['n']:04d} | [{r['title']}]({r['path'].name}) | {r['status']} | {r['date']} |")
    (d / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="docs/adr")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new"); p.add_argument("title"); p.add_argument("--status", default="Proposed", choices=STATUSES)
    p.add_argument("--deciders", default="agent (pending human review)")
    sub.add_parser("list")
    p = sub.add_parser("status"); p.add_argument("n", type=int); p.add_argument("status", choices=STATUSES)
    p = sub.add_parser("supersede"); p.add_argument("n", type=int); p.add_argument("title")
    p.add_argument("--deciders", default="agent (pending human review)")
    sub.add_parser("index")
    a = ap.parse_args()
    d = Path(a.dir)

    if a.cmd == "new":
        n, path = create(d, a.title, a.status, a.deciders)
        print(f"Created {path} (ADR-{n:04d}, {a.status})")
    elif a.cmd == "list":
        for r in records(d):
            print(f"ADR-{r['n']:04d}  {r['status']:<11} {r['title']}")
    elif a.cmd == "status":
        r = find(d, a.n); set_status(r["path"], a.status)
        print(f"ADR-{a.n:04d} → {a.status}")
    elif a.cmd == "supersede":
        old = find(d, a.n)
        n, path = create(d, a.title, "Proposed", a.deciders, supersedes=old)
        set_status(old["path"], f"Superseded by [ADR-{n:04d}]({path.name})")
        print(f"Created {path}; ADR-{a.n:04d} marked superseded")
    if a.cmd != "list":
        write_index(d)


if __name__ == "__main__":
    main()
