#!/usr/bin/env python3
"""Manage numbered feature specs and trace acceptance criteria to code. Stdlib only.

  spec.py new "Title" [--owner "agent"]
  spec.py list
  spec.py status <n> <Draft|Approved|Implemented|Superseded>
  spec.py trace <n> | --all       # exit 1 if any AC is uncovered
  spec.py index
Global: --dir docs/specs
"""
import argparse
import datetime as dt
import os
import re
import sys
from pathlib import Path

TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "template.md"
STATUSES = ["Draft", "Approved", "Implemented", "Superseded"]
FILE_RE = re.compile(r"^(\d{4})-.+\.md$")
SKIP_DIRS = {".git", "node_modules", "dist", "build", ".next", "vendor", "__pycache__",
             ".venv", "venv", "coverage", ".forge", ".claude", ".agents", "target"}
CODE_EXT = {".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".py", ".go", ".rb", ".rs", ".java",
            ".kt", ".swift", ".php", ".cs", ".vue", ".svelte", ".feature", ".spec", ".liquid"}


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60] or "spec"


def specs(d):
    out = []
    for p in sorted(d.glob("*.md")):
        m = FILE_RE.match(p.name)
        if not m:
            continue
        text = p.read_text(encoding="utf-8")
        n = int(m.group(1))
        title = re.search(r"^# SPEC-\d+:\s*(.+)$", text, re.M)
        status = re.search(r"^- \*\*Status:\*\*\s*(.+)$", text, re.M)
        acs = sorted(set(re.findall(rf"\bS{n}-AC\d+\b", text)), key=lambda x: int(x.split("AC")[1]))
        out.append({"n": n, "path": p, "title": title.group(1).strip() if title else p.stem,
                    "status": status.group(1).strip() if status else "?", "acs": acs})
    return out


def find(d, n):
    for s in specs(d):
        if s["n"] == n:
            return s
    sys.exit(f"Spec {n} not found in {d}")


def scan_code(root, spec_dir):
    """Return {AC-id: [file:line, ...]} for every S<n>-AC<m> mention outside the specs folder."""
    hits = {}
    pat = re.compile(r"\bS\d+-AC\d+\b")
    spec_dir = spec_dir.resolve()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [x for x in dirnames if x not in SKIP_DIRS and not x.startswith(".")]
        if Path(dirpath).resolve() == spec_dir:
            continue
        for f in filenames:
            p = Path(dirpath) / f
            if p.suffix not in CODE_EXT or p.stat().st_size > 2_000_000:
                continue
            try:
                for i, line in enumerate(p.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
                    for ac in pat.findall(line):
                        hits.setdefault(ac, []).append(f"{p.relative_to(root)}:{i}")
            except OSError:
                pass
    return hits


def write_index(d):
    lines = ["# Specs", "", "Generated by `spec.py index`.", "",
             "| # | Title | Status | Criteria |", "|---|-------|--------|----------|"]
    for s in specs(d):
        lines.append(f"| {s['n']:04d} | [{s['title']}]({s['path'].name}) | {s['status']} | {len(s['acs'])} |")
    (d / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="docs/specs")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new"); p.add_argument("title"); p.add_argument("--owner", default="agent (pending human review)")
    sub.add_parser("list")
    p = sub.add_parser("status"); p.add_argument("n", type=int); p.add_argument("status", choices=STATUSES)
    p = sub.add_parser("trace"); p.add_argument("n", type=int, nargs="?"); p.add_argument("--all", action="store_true")
    sub.add_parser("index")
    a = ap.parse_args()
    d = Path(a.dir)

    if a.cmd == "new":
        d.mkdir(parents=True, exist_ok=True)
        n = max([s["n"] for s in specs(d)] or [0]) + 1
        body = (TEMPLATE.read_text(encoding="utf-8").replace("{{number}}", f"{n:04d}")
                .replace("{{n}}", str(n)).replace("{{title}}", a.title)
                .replace("{{date}}", dt.date.today().isoformat()).replace("{{owner}}", a.owner))
        path = d / f"{n:04d}-{slugify(a.title)}.md"
        path.write_text(body, encoding="utf-8")
        print(f"Created {path} (SPEC-{n:04d}, criteria prefix S{n}-AC)")
    elif a.cmd == "list":
        for s in specs(d):
            print(f"SPEC-{s['n']:04d}  {s['status']:<12} {len(s['acs']):>2} ACs  {s['title']}")
    elif a.cmd == "status":
        s = find(d, a.n)
        text = s["path"].read_text(encoding="utf-8")
        text = re.sub(r"^(- \*\*Status:\*\*\s*).+$", lambda m: m.group(1) + a.status, text, count=1, flags=re.M)
        s["path"].write_text(text, encoding="utf-8")
        print(f"SPEC-{a.n:04d} → {a.status}")
    elif a.cmd == "trace":
        targets = specs(d) if a.all or a.n is None else [find(d, a.n)]
        hits = scan_code(Path("."), d)
        missing = 0
        for s in targets:
            print(f"SPEC-{s['n']:04d} {s['title']} [{s['status']}]")
            if not s["acs"]:
                print("  (no acceptance criteria found)")
            for ac in s["acs"]:
                where = hits.get(ac)
                if where:
                    print(f"  ✓ {ac}  {', '.join(where[:3])}{' …' if len(where) > 3 else ''}")
                else:
                    missing += 1
                    print(f"  ✗ {ac}  not referenced in any test or code")
        print(f"\n{missing} uncovered criteria" if missing else "\nAll criteria referenced.")
        sys.exit(1 if missing else 0)
    if a.cmd in ("new", "status", "index"):
        write_index(d)


if __name__ == "__main__":
    main()
